"""Audit the schwa tables against Wiktionary and pack the corrections.

Indonesian headwords on en.wiktionary.org mark the pepet vowel: "ê" is /ə/,
"é" and "è" are not. Where a fully marked headword reads a word with fewer
schwas than the lexicon and dictionary do, Wiktionary wins, and where neither
lists the word at all, Wiktionary places it. Both go into
src/data/schwa-wiktionary.ts. A word with more than one etymology is a
homograph, whether or not every sense is marked, and is left to
data/homographs-verified.tsv: Wiktionary marks only the noun sense of "seri",
/séri/, and says nothing about /səri/, radiance.

Of a word the tables already list, only a reading that removes a schwa is
taken. The two sources fail in
opposite directions: the dictionary over-reads the pepet in words KBBI marks
"é" (bébék, mérah, cétak), and Wiktionary over-marks "ê" in words KBBI marks
"é" (cêcêr for /cécér/, sênjang for /sénjang/). A reading that adds a schwa
is printed for review instead. A word the homograph table already splits by
part of speech is left to that rule.

A reading counts only when the marked headword and the IPA line agree. Each
alone is unreliable. The IPA is typed by hand and contradicts the headword
often: "bènsin" carries /bənˈsin/, and "pênganggaran" carries /peŋ.aŋˈɡar.an/.
The headword is sometimes marked with "ê" where /ɛ/ is meant: "bawêl" and
"rêwêl" sit next to /ˈbawɛl/ and /ˈrɛwɛl/, and KBBI has /bawél/ and /réwél/.

Dev-only: run once per Wiktionary refresh. The input is the kaikki.org
extract of the Indonesian Wiktionary; it is not vendored.

    python3 scripts/dump-wiktionary.py <kaikki.org-dictionary-Indonesian.jsonl>

The audit is printed to stdout as `word  old  new  taken|added|review`, one
word per line, so a refresh can be reviewed before it is committed.

Source: https://kaikki.org/dictionary/Indonesian/ (CC BY-SA 4.0).
"""

